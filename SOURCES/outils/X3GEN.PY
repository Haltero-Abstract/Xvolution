# X3GEN.PY : 06XLOGO.OBJ (3Dreams) -> XLOGO3D.S, data of the X logo turning
#   behind the menu (MENU.S) : vertices, faces, BSP tree, colours.
#   Same object, same shading as the 16-colour mode of 3Dreams :
#   2 materials (C lines), 7 shades each (matpal), level = |nz| (flat).
#   python X3GEN.PY 06XLOGO.OBJ XLOGO3D.S
import sys, math
V = []; F = []; T = []; C = {}
for l in open(sys.argv[1]):
    t = l.split()
    if not t or t[0].startswith(';'): continue
    if t[0] == 'V': V.append(tuple(int(x) for x in t[1:4]))
    elif t[0] == 'F': F.append((int(t[1]) - 1, [int(x) for x in t[2:]]))
    elif t[0] == 'T': T.append(tuple(int(x) for x in t[1:5]))
    elif t[0] == 'C': C[int(t[1]) - 1] = tuple(int(x) & 15 for x in t[2:5])
def sub(a, b): return (a[0]-b[0], a[1]-b[1], a[2]-b[2])
def cross(a, b): return (a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0])
out = []
w = out.append
w('; XLOGO3D.S : generated by outils\\X3GEN.PY from 3Dreams OBJ\\06XLOGO.OBJ')
w('; (included by MENU.S)')
w('X3_NV           equ     %d' % len(V))
w('X3_NF           equ     %d' % len(F))
w('X3_NT           equ     %d' % len(T))
w('x3_v:')
for v in V: w('                dc.w    %d,%d,%d' % v)
# face : n.w, material.w, unit normal x,y,z (x 16384).w, 8 indices (bytes) = 18 -> 20
w('x3_f:')
for m, idx in F:
    assert 3 <= len(idx) <= 8
    n = [0, 0, 0]                       # Newell normal
    for i in range(len(idx)):
        a, b = V[idx[i]], V[idx[(i+1) % len(idx)]]
        n[0] += (a[1]-b[1])*(a[2]+b[2]); n[1] += (a[2]-b[2])*(a[0]+b[0]); n[2] += (a[0]-b[0])*(a[1]+b[1])
    ln = math.sqrt(sum(x*x for x in n))
    u = [int(round(x/ln*16383)) for x in n]
    ii = idx + [0]*(8-len(idx))
    w('                dc.w    %d,%d,%d,%d,%d' % (len(idx), m, u[0], u[1], u[2]))
    w('                dc.b    ' + ','.join(str(x) for x in ii))
    w('                dc.w    0')
# BSP node : first.w count.w front.w back.w a.w b.w c.w 0.w d.l = 20 bytes
#   plane : cross3 of the 1st 3 vertices of its 1st face (as bspplanes)
w('x3_t:')
for first, cnt, fr, bk in T:
    idx = F[first][1]
    n = cross(sub(V[idx[1]], V[idx[0]]), sub(V[idx[2]], V[idx[0]]))
    assert all(abs(x) < 32768 for x in n)
    d = sum(n[i]*V[idx[0]][i] for i in range(3))
    w('                dc.w    %d,%d,%d,%d,%d,%d,%d,0' % (first, cnt, fr, bk, n[0], n[1], n[2]))
    w('                dc.l    %d' % d)
# colours 1..14 : material m, shade j (matpal), RGB565 of the STE level
w('x3_col:         dc.w    0')
nmat = 2; nsh = 14 // nmat
cols = []
for m in range(nmat):
    for j in range(nsh):
        lev = 13 if nsh == 1 else j*13//(nsh-1)
        f = 1066 + 174*lev
        r, g, b = [min(15, (c*f + 1664)//3328) for c in C[m]]
        r, g, b = r*17, g*17, b*17
        cols.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
w('                dc.w    ' + ','.join('$%04X' % c for c in cols))
# vertex normals (vertnorms) : average of the unit normals of the faces
#   around the vertex, unit x 16384 (Gouraud : the DSP lights them)
acc = [[0.0, 0.0, 0.0] for _ in V]
for m, idx in F:
    n = cross(sub(V[idx[1]], V[idx[0]]), sub(V[idx[2]], V[idx[0]]))
    ln = math.sqrt(sum(x*x for x in n)) or 1
    for i in idx:
        for k in range(3): acc[i][k] += n[k]/ln
w('x3_vn:')
for a in acc:
    ln = math.sqrt(sum(x*x for x in a)) or 1
    w('                dc.w    %d,%d,%d' % tuple(int(round(x/ln*16384)) if abs(x/ln) < 0.99999 else int(math.copysign(16383, x)) for x in a))
# Gouraud ramps (mkramp + matrgbt, materials) : per material 48 + 128 + 48
#   RGB565 ; 128 shades over the 14 colours c*(1066+174 i)/3328, white
#   highlight from SPEC 104
SPEC = 104
w('x3_ramp:')
for m in range(nmat):
    rgb = [[(c*17*(1066+174*i))//3328 for c in C[m]] for i in range(14)]
    r128 = []
    for d7 in range(128):
        k, f = divmod(d7*13, 127)
        if k >= 13: k, f = 12, 127
        cc = []
        for ch in range(3):
            c = (rgb[k][ch]*(127-f) + rgb[k+1][ch]*f)//127
            if d7 >= SPEC: c += ((255-c)*(d7-SPEC))//(127-SPEC)
            cc.append(c)
        r128.append(((cc[0] >> 3) << 11) | ((cc[1] >> 2) << 5) | (cc[2] >> 3))
    full = [r128[0]]*48 + r128 + [r128[127]]*48
    for i in range(0, 224, 16):
        w('                dc.w    ' + ','.join('$%04X' % c for c in full[i:i+16]))
w('                even')
open(sys.argv[2], 'w', newline='\r\n').write('\n'.join(out) + '\n')
