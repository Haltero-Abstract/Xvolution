# SHIPGEN.PY : the player's ship (Atari logo) in 3D, drawn smooth :
#   the logo is extruded (thickness Z0..Z1 like the old 9 boxes), seen in
#   perspective (FOC / z) from each of the 5 x 3 places of the sprites, so
#   its side walls show ; supersampled 4 x 4 ; front face lit with a bevel,
#   walls shaded by their direction (side / top / bottom colours of the
#   boxes) ; edges softened towards a dark outline (no alpha on the Falcon).
#   -> SHIPGFX.S : 3 forms x 15 places, each : w, h, offx, offy, pixels
#   python SHIPGEN.PY SHIPGFX.S [preview.png]
import sys
import numpy as np
from PIL import Image
FOC, SHIP_Z = 320, 300
SPR_NX, SPR_DX, SPR_WY = 5, 58, (-70, 0, 80)
Z0, Z1 = 1.0, 9.0                               # thickness (world units)
OBX, OBY = 0.10, 0.40                           # slight tilt : the thickness shows
                                                #  right and below (away from the light)
SS = 4
KEY = 0xF81F
HALF = 30                                       # drawn in 60 x 60 around the place
def shape(x, y):
    """0 outside, 1 centre bar, 2 arm (world units of the model)"""
    r = np.zeros(x.shape, np.int8)
    ok = (y >= -15.5) & (y <= 15.5)
    t = np.clip((y + 15.5) / 31.0, 0, 1)
    xi = 4.0 + 9.5 * t ** 2.3
    xo = 7.0 + 13.5 * t ** 1.9
    ax = np.abs(x)
    r[ok & (ax >= xi) & (ax <= xo)] = 2
    r[ok & (ax <= 2.2)] = 1
    return r
FORMS = [((240, 240, 245), (240, 240, 245)),
         ((240, 240, 245), (225, 30, 30)),
         ((225, 30, 30), (225, 30, 30))]
OUTL = np.array((25, 25, 30), float)
L = np.array((-0.55, -0.65, 0.52)); L /= np.linalg.norm(L)

def render(wx, wy):
    # tilt per place : the deep slices slide towards the centre of the
    #   screen (perspective, made stronger so the places differ clearly)
    obx = OBX - 0.55 * wx / 116.0
    oby = OBY - 0.25 * wy / 80.0
    n = 2 * HALF * SS
    g = (np.arange(n) + 0.5) / SS - HALF        # screen offset from the place centre
    sx, sy = np.meshgrid(g, g)
    scx = wx * FOC / SHIP_Z
    scy = wy * FOC / SHIP_Z
    kind = np.zeros(sx.shape, np.int8)
    face = np.zeros(sx.shape, np.int8)          # 0 front, 1 wall
    zhit = np.zeros(sx.shape)
    for z in np.arange(Z0, Z1 + 1e-6, 0.25):    # nearest first
        zz = SHIP_Z + z
        x = (sx + scx) * zz / FOC - wx - (z - Z0) * obx
        y = (sy + scy) * zz / FOC - wy - (z - Z0) * oby
        k = shape(x, y)
        new = (kind == 0) & (k > 0)
        kind[new] = k[new]
        face[new] = 0 if z == Z0 else 1
        zhit[new] = z
    zz = SHIP_Z + zhit
    x = (sx + scx) * zz / FOC - wx - (zhit - Z0) * obx
    y = (sy + scy) * zz / FOC - wy - (zhit - Z0) * oby
    e = 0.7
    gx = (shape(x + e, y) > 0).astype(float) - (shape(x - e, y) > 0)
    gy = (shape(x, y + e) > 0).astype(float) - (shape(x, y - e) > 0)
    return kind, face, gx, gy, zhit

def bevel(cov):
    p = np.pad(cov, 1)
    gx = (p[1:-1, 2:] - p[1:-1, :-2]) + 0.5 * (p[:-2, 2:] - p[:-2, :-2] + p[2:, 2:] - p[2:, :-2])
    gy = (p[2:, 1:-1] - p[:-2, 1:-1]) + 0.5 * (p[2:, :-2] - p[:-2, :-2] + p[2:, 2:] - p[:-2, 2:])
    nx, ny, nz = -gx * 0.8, -gy * 0.8, np.ones(cov.shape)
    nl = np.sqrt(nx * nx + ny * ny + nz * nz)
    d = (nx * L[0] + ny * L[1] + nz * L[2]) / nl
    return 0.55 + 0.6 * np.clip(d, 0, 1)

out = ['; SHIPGFX.S : generated by OUTILS\\SHIPGEN.PY : the ship in 3D (Atari logo',
       ';   extruded, perspective of each place), 3 forms x %d places' % (SPR_NX * len(SPR_WY)),
       ';   entry : w, h, offx, offy (from the place centre), w x h RGB565 (key $%04X)' % KEY,
       'ship_imgs:']
data = []
labels = []
prev = Image.new('RGB', (SPR_NX * 64 * 3, len(SPR_WY) * 64), (180, 160, 120))
n = 2 * HALF
for f, (cc, ca) in enumerate(FORMS):
    for iy, wy in enumerate(SPR_WY):
        for ix in range(SPR_NX):
            wx = (ix - SPR_NX // 2) * SPR_DX
            kind, face, gx, gy, zhit = render(wx, wy)
            K = kind.reshape(n, SS, n, SS)
            cov = (K > 0).mean(axis=(1, 3))
            base = np.where((kind == 1)[..., None], np.array(cc, float), np.array(ca, float))
            wall = face == 1
            ax, ay = np.abs(gx), np.abs(gy)
            wsh = np.where(ax >= ay, 0.70, np.where(gy > 0, 0.85, 0.50))
            wsh = wsh * (1.0 - 0.25 * (zhit - Z0) / (Z1 - Z0))
            sh = np.where(wall, wsh, 1.0)
            col = (base * sh[..., None]).reshape(n, SS, n, SS, 3)
            m = (K > 0)[..., None]
            cnt = np.maximum(1, (K > 0).sum(axis=(1, 3)))[..., None]
            col = (col * m).sum(axis=(1, 3)) / cnt
            F = ((face == 0) & (kind > 0)).reshape(n, SS, n, SS)
            front = F.mean(axis=(1, 3)) > 0.5 * cov
            col = np.where(front[..., None], col * (bevel(cov) / 0.85)[..., None], col)
            col = np.clip(col, 0, 255)
            a = np.clip((cov - 0.2) / 0.6, 0, 1)[..., None]
            col = OUTL + (col - OUTL) * a
            vis = cov >= 0.2
            ys, xs = np.nonzero(vis)
            y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
            lab = 'shp_%d_%d_%d' % (f, iy, ix)
            labels.append(lab)
            data.append('%s:  dc.w    %d,%d,%d,%d' % (lab, x1 - x0, y1 - y0, x0 - HALF, y0 - HALF))
            for yy in range(y0, y1):
                row = []
                for xx in range(x0, x1):
                    if not vis[yy, xx]:
                        row.append(KEY); continue
                    r, g, b = (int(v) for v in col[yy, xx])
                    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
                    if v == KEY: v = 0xF81E
                    row.append(v)
                    prev.putpixel(((f * SPR_NX + ix) * 64 + xx + 2, iy * 64 + yy + 2), (r, g, b))
                for i in range(0, len(row), 16):
                    data.append('                dc.w    ' + ','.join('$%04X' % v for v in row[i:i + 16]))
for i in range(0, 45, 5):
    out.append('                dc.l    ' + ','.join(labels[i:i + 5]))
out += data
out.append('                even')
open(sys.argv[1], 'w', newline='\r\n').write('\n'.join(out) + '\n')
if len(sys.argv) > 2:
    prev.resize((prev.size[0] * 2, prev.size[1] * 2), Image.NEAREST).save(sys.argv[2])
